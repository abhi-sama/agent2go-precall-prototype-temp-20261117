import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { DEFAULT_THEME, THEME_SLUGS } from "./themes"

describe("theme catalogue", () => {
  it("matches the theme module generated by `astryx theme add`", () => {
    const generated = readFileSync(new URL("../../astryx-themes.ts", import.meta.url), "utf8")
    const record = JSON.parse(/@astryx-theme-record (\{.*\})/.exec(generated)![1]) as { themes: Record<string, string>; defaultThemeSlug: string }
    expect([...THEME_SLUGS].sort()).toEqual(Object.keys(record.themes).sort())
    expect(DEFAULT_THEME).toBe(record.defaultThemeSlug)
  })
})

describe("self-hosted theme fonts", () => {
  it("covers every family each theme's Google Fonts stylesheet asks for", () => {
    const fonts = readFileSync(new URL("./theme-fonts.ts", import.meta.url), "utf8")
    for (const slug of THEME_SLUGS) {
      const css = readFileSync(new URL(`../../../node_modules/@astryxdesign/theme-${slug}/fonts.css`, import.meta.url), "utf8")
      for (const [, family] of css.matchAll(/family=([^:&']+)/g)) {
        const pkg = family.replace(/\+/g, "-").toLowerCase()
        expect(fonts, `${slug}: ${family}`).toContain(`@fontsource/${pkg}/`)
      }
    }
  })

  it("the registry renders every theme in the catalogue", () => {
    const registry = readFileSync(new URL("./astryx-registry.ts", import.meta.url), "utf8")
    for (const slug of THEME_SLUGS) expect(registry).toContain(`@astryxdesign/theme-${slug}/theme.css`)
    expect(registry).not.toMatch(/import "[^"]*fonts\.css"/)
  })
})
