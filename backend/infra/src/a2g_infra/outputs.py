"""Write the provisioned stack's coordinates for the frontend and the test harness.

* ``frontend/amplify_outputs.json``: the standard Amplify Gen2 outputs file the app
  passes to ``Amplify.configure``, plus a ``custom.a2g`` block for the local stack
  (floci user-pool endpoint, seeded users for the local-only persona quick-switch).
  ``ampx generate outputs`` is not used because it would call AWS.
* ``frontend/.env.local``: switches the data adapter from the mock to AppSync and inlines
  the outputs as ``NEXT_PUBLIC_AMPLIFY_OUTPUTS`` (the app reads them at build time).
* ``backend/infra/.state/outputs.json``: everything the API-as-persona tests need.

All three files are gitignored and local-only.
"""

from __future__ import annotations

import json

from .config import (
    ENDPOINT,
    FRONTEND,
    LOCAL_PASSWORD,
    REGION,
    STATE_DIR,
    WEB_ORIGIN,
)

PERSONA_KEY = {"MSL": "msl", "Director": "director", "Executive": "executive", "Administrator": "admin"}


def _amplify_outputs(fe: dict, users: list[dict]) -> dict:
    # The Amplify stack outputs groups already in amplify_outputs shape: [{"MSL": {...}}, ...].
    groups = fe.get("groups") or [{g: {"precedence": i}} for i, g in enumerate(["MSL", "Director", "Executive", "Administrator"])]
    return {
        "version": "1.3",
        "auth": {
            "aws_region": fe["region"],
            "user_pool_id": fe["user_pool_id"],
            "user_pool_client_id": fe["client_id"],
            "standard_required_attributes": ["email"],
            "username_attributes": ["email"],
            "user_verification_types": ["email"],
            "groups": groups,
            "mfa_configuration": "OFF",
            "mfa_methods": [],
            "password_policy": {
                "min_length": 8,
                "require_lowercase": True,
                "require_numbers": True,
                "require_symbols": True,
                "require_uppercase": True,
            },
            "unauthenticated_identities_enabled": False,
        },
        "data": {
            "url": fe["graphql_url_host"],
            "aws_region": REGION,
            "default_authorization_type": "AMAZON_COGNITO_USER_POOLS",
            "authorization_types": [],
        },
        "custom": {
            "a2g": {
                "env": "local",
                "user_pool_endpoint": ENDPOINT,
                # floci answers no CORS preflights: the browser goes through this same-origin
                # Next.js rewrite (frontend/next.config.ts) instead of calling floci directly.
                "proxy_path": "/_floci",
                "web_origin": WEB_ORIGIN,
                # Local-only persona quick-switch: synthetic people, one shared local password.
                "local_password": LOCAL_PASSWORD,
                "seeded_users": [
                    {
                        "userId": u["user_id"],
                        "email": u["email"],
                        "fullName": u["full_name"],
                        "persona": PERSONA_KEY[u["cognito_group"]],
                        "territoryId": u["territory_id"],
                        "identityStatus": u["identity_status"],
                    }
                    for u in users
                ],
            }
        },
    }


def write(fe: dict, db: dict, fn_arn: str, users: list[dict], store: dict, agent: dict) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    state = {
        "endpoint": ENDPOINT,
        "fe": {k: v for k, v in fe.items() if k != "outputs"},
        "be": {
            "api_function_arn": fn_arn,
            "db_port": db["port"],
            "owner_dsn": db["owner_dsn"],
            "app_dsn": db["app_dsn_host"],
            "agent_url": agent["url"],
        },
        "fe_store": store,
        "local_password": LOCAL_PASSWORD,
        "users": users,
    }
    (STATE_DIR / "outputs.json").write_text(json.dumps(state, indent=2) + "\n")
    amplify_outputs = _amplify_outputs(fe, users)
    (FRONTEND / "amplify_outputs.json").write_text(json.dumps(amplify_outputs, indent=2) + "\n")
    compact = json.dumps(amplify_outputs, separators=(",", ":"))
    assert "'" not in compact and "$" not in compact, "outputs must survive dotenv single-quoting"
    (FRONTEND / ".env.local").write_text(
        "# Generated by backend/infra/scripts/up.sh for the local floci stack. Do not commit.\n"
        "NEXT_PUBLIC_APP_ENV=local\n"
        "NEXT_PUBLIC_DATA_ADAPTER=appsync\n"
        f"NEXT_PUBLIC_AMPLIFY_OUTPUTS='{compact}'\n"
    )
